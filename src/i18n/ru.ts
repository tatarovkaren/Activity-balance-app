/** «год / года / лет» для числа. */
const ruYears = (n: number) => {
  const a = n % 10;
  const b = n % 100;
  if (a === 1 && b !== 11) return 'год';
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return 'года';
  return 'лет';
};

