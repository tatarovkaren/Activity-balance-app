import { describe, expect, it } from 'vitest';
import { parseFatSecretPdf, type PdfLine } from './importers';

// строка PDF из ячеек: [x, текст]
const L = (...cells: [number, string][]): PdfLine => ({ page: 1, items: cells.map(([x, str]) => ({ x, w: 30, str })) });
const HEAD = L([40, 'Продукт'], [250, 'Кал (ккал)'], [300, 'Жир (г)'], [350, 'Н/жир (г)'], [400, 'Углев (г)'], [450, 'Клетч (г)'], [500, 'Белк (г)']);

describe('FatSecret PDF', () => {
  it('блоки дней: дата → приёмы пищи → «Всего»; сводка периода и колонтитулы не берутся', () => {
    const lines: PdfLine[] = [
      L([40, 'Сводка за период']),
      L([40, '01.11.2026 – 02.11.2026']),
      HEAD,
      L([40, 'Всего'], [250, '3 900'], [300, '120,5'], [350, '30'], [400, '400'], [450, '20'], [500, '210']),
      L([40, 'понедельник, 1 ноября 2026']),
      HEAD,
      L([40, 'Завтрак'], [250, '500'], [300, '20'], [350, '5'], [400, '60'], [450, '4'], [500, '25']),
      L([40, 'Итого'], [250, '500'], [300, '20'], [350, '5'], [400, '60'], [450, '4'], [500, '25']),
      L([40, 'Обед'], [250, '1 400'], [300, '40'], [350, '10'], [400, '150'], [450, '8'], [500, '95']),
      L([40, 'Всего'], [250, '1 900'], [300, '60,3'], [350, '15'], [400, '210'], [450, '12'], [500, '120,4']),
      L([40, 'Создано в fatsecret 17.11.2026'], [500, 'стр. 1']),
      L([40, 'вторник, 2 ноября 2026']),
      L([40, 'Всего'], [250, '2000'], [300, '60'], [400, '190']),
      L([40, 'среда, 3 ноября 2026']),
      L([40, 'Всего'], [250, '0']),
    ];
    const r = parseFatSecretPdf(lines);
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.days).toEqual([
      { date: '2026-11-01', kcal: 1900, fat: 60.3, carbs: 210, protein: 120.4 },
      { date: '2026-11-02', kcal: 2000, fat: 60, carbs: 190, protein: undefined },
    ]);
    expect(r.skipped).toBe(1);
  });

  it('строка дня с датой и итогами (как в CSV), английский отчёт', () => {
    const head = L([40, 'Date'], [250, 'Calories'], [300, 'Fat (g)'], [350, 'Sat Fat (g)'], [400, 'Carbs (g)'], [500, 'Protein (g)']);
    const r = parseFatSecretPdf([
      head,
      L([40, 'Monday, November 16, 2026'], [250, '1,499'], [300, '52.3'], [350, '10'], [400, '180.2'], [500, '90']),
      L([60, 'Breakfast'], [250, '400'], [300, '10'], [400, '50'], [500, '20']),
    ]);
    expect(r).toEqual({ ok: true, skipped: 0, days: [{ date: '2026-11-16', kcal: 1499, fat: 52.3, carbs: 180.2, protein: 90 }] });
  });

  it('нет заголовка столбцов — ошибка', () => {
    expect(parseFatSecretPdf([L([40, 'понедельник, 1 ноября 2026']), L([40, 'Всего'], [250, '1900'])])).toEqual({ ok: false, error: 'fatsecretNoHeader' });
  });
});

// Настоящий отчёт FatSecret (Карен, 18.11.2026): шапка с датой и сайтом на каждой странице,
// приёмы пищи со строкой «Всего», день продолжается на следующей странице, в конце «Всего» за день.
describe('FatSecret PDF — раскладка реального отчёта', () => {
  it('итог дня = последняя «Всего» в блоке даты', () => {
    const head = L([200, 'Кал'], [245, 'Жир'], [290, 'Н/жир'], [335, 'Углев'], [380, 'Клетч'], [420, 'Сахар'], [460, 'Белк'], [500, 'Натри'], [540, 'Холес'], [580, 'Калий']);
    const page = (n: number, body: PdfLine[]): PdfLine[] => [
      { ...L([30, 'Food Diary Report - Detailed Report'], [250, 'среда, ноября 18, 2026'], [520, 'www.fatsecret.ru']), page: n },
      { ...L([30, 'среда, ноября 18, 2026']), page: n },
      head,
      L([200, '(ккал)'], [245, '(г)'], [290, '(г)']),
      ...body,
      L([520, 'Страница ' + n]),
    ];
    const r = parseFatSecretPdf([
      ...page(1, [L([30, 'Завтрак']), L([30, 'Цветная Капуста'], [200, '9'], [245, '0,04'], [290, '0,011'], [335, '1,86'], [460, '0,69'], [580, '106']), L([30, '35 г']),
        L([30, 'Всего'], [200, '503'], [245, '20,91'], [290, '0,149'], [335, '42,35'], [380, '0,9'], [420, '0,84'], [460, '35,65'], [500, '10'], [540, '493,6'], [580, '106'])]),
      ...page(3, [L([30, 'Всего'], [200, '513'], [245, '19,95'], [335, '50,81'], [460, '37,37']),
        L([30, 'Всего'], [200, '1700'], [245, '57,16'], [290, '0,991'], [335, '172,01'], [380, '19,66'], [420, '43,89'], [460, '130,06'], [500, '86'], [540, '561,6'], [580, '1624'])]),
    ]);
    expect(r).toEqual({ ok: true, skipped: 0, days: [{ date: '2026-11-18', kcal: 1700, fat: 57.2, carbs: 172, protein: 130.1 }] });
  });
});
